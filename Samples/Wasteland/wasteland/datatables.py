"""Export the Python game data to Unreal DataTables.

Writes one CSV per table plus ``WastelandRows.h``, a C++ header with the
matching ``USTRUCT`` row types. Drop the header into your game module, compile,
and then import each CSV as a DataTable with the matching row struct (or let
``unreal_tools/setup_wasteland.py`` import them for you).

    python -m wasteland.datatables --out Exports
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

from .anomalies import ANOMALY_TYPES
from .creatures import CREATURES
from .factions import FACTIONS
from .items import ITEMS
from .special import PERKS
from .world import LOOT_TABLES

# Row struct name -> (columns: [(name, C++ type)], rows: iterable of dicts)


def _items():
    for item in ITEMS.values():
        yield {
            "Name": item.id, "DisplayName": item.name, "Category": item.category.value,
            "WeightKg": item.weight_kg, "Value": item.value, "SizeX": item.size[0],
            "SizeY": item.size[1], "MaxStack": item.stack, "Origin": item.origin,
            "MeshHint": item.mesh_hint, "EffectsJson": json.dumps(item.effects),
        }


def _creatures():
    for c in CREATURES.values():
        yield {
            "Name": c.id, "DisplayName": c.name, "Origin": c.origin, "Health": c.health,
            "Damage": c.damage, "SpeedMps": c.speed_mps, "SightM": c.sight_m,
            "HearingMult": c.hearing_mult, "AttackRangeM": c.attack_range_m,
            "AttackCooldown": c.attack_cooldown, "bNocturnal": c.nocturnal,
            "bUnderground": c.underground, "PackMin": c.pack[0], "PackMax": c.pack[1],
            "XP": c.xp, "MeshHint": c.mesh_hint, "ResistJson": json.dumps(c.resist),
        }


def _anomalies():
    for a in ANOMALY_TYPES.values():
        yield {
            "Name": a.id, "DisplayName": a.name, "DamageType": a.dtype.value,
            "RadiusM": a.radius_m, "Damage": a.damage, "Cooldown": a.cooldown_sec,
            "Visibility": a.visible, "NiagaraSystem": a.vfx_hint,
            "LightColor": "(R={:.2f},G={:.2f},B={:.2f},A=1.0)".format(*a.light_rgb),
        }


def _factions():
    for f in FACTIONS.values():
        yield {
            "Name": f.id, "DisplayName": f.name, "Origin": f.origin,
            "Currency": f.currency, "HomePOI": f.home,
            "bHostileByDefault": f.hostile_by_default, "Persona": f.persona,
        }


def _perks():
    for p in PERKS.values():
        yield {
            "Name": p.id, "DisplayName": p.name, "Stat": p.stat,
            "RequiredRank": p.required_rank, "MinLevel": p.min_level,
            "Description": p.description, "EffectsJson": json.dumps(p.effects),
        }


def _loot():
    for table, entries in LOOT_TABLES.items():
        for item_id, weight, max_qty in entries:
            yield {"Name": f"{table}.{item_id}", "Table": table, "ItemId": item_id,
                   "Weight": weight, "MaxQuantity": max_qty}


TABLES = {
    "FWastelandItemRow": ("DT_Items", _items),
    "FWastelandCreatureRow": ("DT_Creatures", _creatures),
    "FWastelandAnomalyRow": ("DT_Anomalies", _anomalies),
    "FWastelandFactionRow": ("DT_Factions", _factions),
    "FWastelandPerkRow": ("DT_Perks", _perks),
    "FWastelandLootRow": ("DT_Loot", _loot),
}


def _cpp_type(column: str, value) -> str:
    if column == "LightColor":
        return "FLinearColor"
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, int):
        return "int32"
    if isinstance(value, float):
        return "float"
    return "FString"


def export_csv(out_dir: Path) -> dict:
    """Write every table as a CSV. Returns {struct: csv path}."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written = {}
    for struct, (asset_name, rows_fn) in TABLES.items():
        rows = list(rows_fn())
        path = out_dir / f"{asset_name}.csv"
        with path.open("w", newline="", encoding="utf-8") as fh:
            # UE's CSV importer uses the first column as the row name.
            writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
            writer.writeheader()
            for row in rows:
                writer.writerow({k: (str(v).lower() if isinstance(v, bool) else v)
                                 for k, v in row.items()})
        written[struct] = path
    return written


def generate_header(module_api: str = "WASTELAND_API") -> str:
    lines = [
        "// Generated by wasteland.datatables - do not edit by hand.",
        "#pragma once",
        "",
        '#include "CoreMinimal.h"',
        '#include "Engine/DataTable.h"',
        '#include "WastelandRows.generated.h"',
        "",
    ]
    for struct, (_, rows_fn) in TABLES.items():
        first = next(iter(rows_fn()))
        lines += ["USTRUCT(BlueprintType)",
                  f"struct {module_api} {struct} : public FTableRowBase", "{",
                  "\tGENERATED_BODY()", ""]
        for column, value in first.items():
            if column == "Name":
                continue    # the row name
            ctype = _cpp_type(column, value)
            default = {"bool": " = false", "int32": " = 0", "float": " = 0.f"}.get(ctype, "")
            lines += ['\tUPROPERTY(EditAnywhere, BlueprintReadOnly, Category = "Wasteland")',
                      f"\t{ctype} {column}{default};", ""]
        lines += ["};", ""]
    return "\n".join(lines)


def export_all(out_dir: Path, module_api: str = "WASTELAND_API") -> dict:
    written = export_csv(out_dir)
    header = out_dir / "WastelandRows.h"
    header.write_text(generate_header(module_api), encoding="utf-8")
    written["header"] = header
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description="Export Unreal DataTables")
    parser.add_argument("--out", default="Exports")
    parser.add_argument("--api", default="WASTELAND_API",
                        help="Your game module's export macro, e.g. MYGAME_API")
    args = parser.parse_args()
    for name, path in export_all(Path(args.out), args.api).items():
        print(f"{name:>24} -> {path}")


if __name__ == "__main__":
    main()
